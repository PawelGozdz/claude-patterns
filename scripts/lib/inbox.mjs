// scripts/lib/inbox.mjs — odczyt nagłówków skrzynki docs/tasks/_inbox/ i widok maszynowy (index.json).
//
// Wspólne dla `report-deviation.mjs` (zapis i `--list`) i `generate-inbox-index.mjs`. Skrzynka
// zostaje markdownem (rekordy edytuje się w triage), a dashboard i serwer czytają jeden mały
// plik zamiast ponad stu.

import { readFileSync, readdirSync, existsSync } from 'node:fs';
import { join, dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { createRequire } from 'node:module';
import { defaultCategory } from './telemetry-events.mjs';

const REPO_ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..', '..');
const YAML = createRequire(import.meta.url)(join(REPO_ROOT, 'node_modules', 'yaml'));

export const INBOX_DIR = join(REPO_ROOT, 'docs', 'tasks', '_inbox');
export const INDEX_FILE = 'index.json';
export const GENERATED_NOTE = 'GENERATED by scripts/generate-inbox-index.mjs — nie edytuj ręcznie; odtwórz: node scripts/generate-inbox-index.mjs';

/** Nagłówki wszystkich rekordów `*.md` (poza README). Jeden uszkodzony frontmatter nie wywraca listy. */
export function readInboxEntries(dir = INBOX_DIR) {
  if (!existsSync(dir)) return [];
  const rows = [];
  for (const f of readdirSync(dir).filter((n) => n.endsWith('.md') && n !== 'README.md').sort()) {
    const m = readFileSync(join(dir, f), 'utf8').match(/^---\r?\n([\s\S]*?)\r?\n---/);
    if (!m) continue;
    // DEV-orc-062-application: zduplikowany klucz `resolution` → YAMLParseError na `--list` (2026-10-04).
    let fm;
    try {
      fm = YAML.parse(m[1]) || {};
    } catch (e) {
      process.stderr.write(`UWAGA: ${f}: uszkodzony frontmatter (${String(e.message).split('\n')[0]}) — pominięty na liście\n`);
      continue;
    }
    rows.push({ file: f, ...fm });
  }
  return rows;
}

const asList = (v) => (Array.isArray(v) ? v.map(String) : []);
const asDate = (v) => (v === undefined || v === null ? null : String(v instanceof Date ? v.toISOString().slice(0, 10) : v));

/** Rekord skrzynki → pozycja indeksu. Rekord bez `category` dostaje wartość domyślną z triggera. */
export function toIndexEntry(row) {
  return {
    id: row.id || row.file.replace(/\.md$/, ''),
    status: row.status || null,
    trigger: row.trigger || null,
    category: row.category || defaultCategory(row.trigger, row.rule_ref),
    // Do 2026-10-10 skrzynkę karmił wyłącznie /orchestrate; report-deviation czyta brak `sources` tak samo.
    sources: asList(row.sources).length ? asList(row.sources) : ['orchestrate'],
    occurrences: Number.isFinite(row.occurrences) ? row.occurrences : null,
    projects: asList(row.projects),
    first_seen: asDate(row.first_seen),
    last_seen: asDate(row.last_seen),
    // Deklaracja „którą liczbę to poprawi" (TASK-OBS-017); tylko gdy rekord ją ma, żeby indeks nie puchł o null-e.
    ...(row.claim && typeof row.claim === 'object'
      ? {
        claim: {
          metric: row.claim.metric ?? null, direction: row.claim.direction ?? null, threshold: row.claim.threshold ?? null, engine: row.claim.engine ?? null,
          ...(row.claim.process !== undefined ? { process: row.claim.process } : {}),
        },
      }
      : {}),
  };
}

/** Indeks w stałej kolejności (po id), żeby plik w gicie zmieniał się tylko wraz z danymi. */
export function buildIndex(rows) {
  const entries = rows.map(toIndexEntry).sort((a, b) => a.id.localeCompare(b.id));
  return { _generated: GENERATED_NOTE, count: entries.length, entries };
}

export const serializeIndex = (index) => `${JSON.stringify(index, null, 2)}\n`;

// ── postarzanie (TASK-OBS-007, ADR 0011 B4) ─────────────────────────────────────
// Zgłoszenie bez ruchu jest widoczne w wyjściu pre-commit (nigdy nie blokuje commita):
// `promoted` czeka na realizację, `proposed` na triage — i jedno, i drugie gnije po cichu.
export const STALE_AFTER_DAYS = { promoted: 7, proposed: 14 };
const DAY_MS = 24 * 60 * 60 * 1000;

const asMs = (v) => {
  if (v === undefined || v === null) return null;
  const t = v instanceof Date ? v.getTime() : Date.parse(String(v));
  return Number.isFinite(t) ? t : null;
};

/** Rekordy `promoted`/`proposed` bez ruchu dłużej niż próg; ruch = najnowsze z last_seen, reopened_at, first_seen. */
export function staleInboxEntries(rows, now = new Date(), limits = STALE_AFTER_DAYS) {
  const out = [];
  for (const r of rows) {
    const limit = limits[r.status];
    if (!limit) continue;
    const moves = [r.last_seen, r.reopened_at, r.first_seen].map(asMs).filter((t) => t !== null);
    if (!moves.length) continue;
    const days = Math.floor((now.getTime() - Math.max(...moves)) / DAY_MS);
    if (days > limit) out.push({ id: r.id || String(r.file || '').replace(/\.md$/, ''), status: r.status, days, limit });
  }
  return out.sort((a, b) => b.days - a.days || a.id.localeCompare(b.id));
}
