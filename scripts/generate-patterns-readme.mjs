#!/usr/bin/env node
// Generuje .claude/knowledge/patterns/README.md projektu z FAKTYCZNEGO stanu:
//   node scripts/generate-patterns-readme.mjs <project_dir> [patterns_repo]
//
// Po co: README (discovery hub czytany przez agentów w fast-path) był kopiowany RAZ
// z templates/knowledge-patterns-readme-template.md — statycznego szablonu pod NestJS/DDD
// (agregaty, Result<T>, golevelup, architecture/) — i nigdy nie resyncowany. Projekt
// Pythonowy, biblioteka TS czy aplikacja Flutter dostawały README reklamujące kategorie,
// których nie mają, a tabelę „co czytać" wskazującą nieistniejące pliki (audyt floty
// 2026-10-10: ~15 projektów).
//
// Źródła: podlinkowane kategorie (dowiązania i katalogi w patterns/), ich opis z
// METADATA.yml w centrali, `patterns.always` + `patterns.triggers` z runtime.yml (to
// jest prawdziwa odpowiedź na „co czytać przy jakim tasku") i katalogi patterns-local/.
//
// Plik dostaje znacznik GENERATED_MARKER — setup-project.sh nadpisuje tylko README
// z tym znacznikiem, brakujące albo identyczne ze starym szablonem; ręcznie edytowane
// zostawia w spokoju i ostrzega.

import { readFileSync, writeFileSync, existsSync, readdirSync, statSync, lstatSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

let YAML;
try {
  YAML = (await import('yaml')).default;
} catch {
  console.error('  BŁĄD: brak paczki "yaml" — odpal `npm ci` w claude-patterns i spróbuj ponownie.');
  process.exit(1);
}

const GENERATED_MARKER = '<!-- GENERATED by claude-patterns/scripts/generate-patterns-readme.mjs';

const projectDir = process.argv[2];
const REPO = process.argv[3] ?? join(dirname(fileURLToPath(import.meta.url)), '..');
if (!projectDir) { console.error('użycie: generate-patterns-readme.mjs <project_dir> [patterns_repo]'); process.exit(1); }

const patternsDir = join(projectDir, '.claude/knowledge/patterns');
const localDir = join(projectDir, '.claude/knowledge/patterns-local');
const runtimePath = join(projectDir, '.claude/config/runtime.yml');
if (!existsSync(patternsDir)) { console.error(`  brak ${patternsDir} — nic do opisania`); process.exit(1); }
// patterns/ (albo samo README) jako symlink do centrali: zapis nadpisałby claude-patterns/patterns/README.md.
const isLink = (p) => { try { return lstatSync(p).isSymbolicLink(); } catch { return false; } };
if (isLink(patternsDir) || isLink(join(patternsDir, 'README.md'))) {
  console.error(`  odmowa: ${patternsDir} lub jego README.md to symlink — zapis trafiłby poza projekt`);
  process.exit(1);
}

const isDir = (p) => { try { return statSync(p).isDirectory(); } catch { return false; } };
const subdirs = (p) => (isDir(p) ? readdirSync(p).filter((n) => !n.startsWith('.') && isDir(join(p, n))).sort() : []);

const describe = (cat) => {
  const meta = join(REPO, 'patterns', cat, 'METADATA.yml');
  if (!existsSync(meta)) return '';
  const d = String(YAML.parse(readFileSync(meta, 'utf8'))?.description ?? '').replace(/\s+/g, ' ').trim();
  const first = d.split(/(?<=\.)\s/)[0];
  return first.length > 160 ? `${first.slice(0, 157)}…` : first;
};

let runtime = {};
if (existsSync(runtimePath)) runtime = YAML.parse(readFileSync(runtimePath, 'utf8')) ?? {};
const always = runtime.patterns?.always ?? [];
const triggers = runtime.patterns?.triggers ?? [];

const categories = subdirs(patternsDir);
const localCats = subdirs(localDir);

const out = [];
out.push(`${GENERATED_MARKER} — NIE edytuj ręcznie; odświeża go setup-project.sh. -->`);
out.push('# Patterns — `.claude/knowledge/patterns/`', '');
out.push('Wzorce, które orkiestrator i implementerzy czytają przed pisaniem kodu. Ten plik opisuje',
  '**faktyczny** skład tego projektu (kategorie podlinkowane przez setup + kompozycja bloków',
  'z `.claude/config/runtime.yml`). Gdy wywołano cię bez listy `{PATTERNS}`, zacznij od sekcji', '„Zawsze”.', '');

out.push('## Kategorie w tym projekcie', '');
if (categories.length) {
  out.push('| Kategoria | Co obejmuje |', '|---|---|');
  for (const c of categories) out.push(`| \`${c}/\` | ${describe(c) || '_(kategoria lokalna)_'} |`);
} else out.push('_Brak podlinkowanych kategorii._');
out.push('');
if (localCats.length) {
  out.push('Wzorce lokalne projektu (`.claude/knowledge/patterns-local/`, trackowane w gicie): ' +
    localCats.map((c) => `\`${c}/\``).join(', ') + '.', '');
}

out.push('## Zawsze — każdy task (`patterns.always`)', '');
if (always.length) for (const p of always) out.push(`- \`${p}\``);
else out.push('_Kompozycja nie deklaruje półki `always`._');
out.push('');

out.push('## Co czytać przy jakim tasku (`patterns.triggers`)', '');
const useful = triggers.filter((t) => (t.include ?? []).length);
if (useful.length) {
  out.push('| Słowa kluczowe w tasku | Czytaj |', '|---|---|');
  for (const t of useful)
    out.push(`| ${(t.keywords ?? []).slice(0, 8).join(', ')}${(t.keywords ?? []).length > 8 ? ', …' : ''} | ${t.include.map((p) => `\`${p}\``).join(', ')} |`);
} else out.push('_Brak triggerów w kompozycji._');
out.push('');

out.push('## Jak wzorce trafiają do promptów', '',
  '1. Orkiestrator czyta `.claude/config/runtime.yml` (materializowany ze `stack_blocks`).',
  '2. `patterns.always` + pasujące `patterns.triggers` → `{PATTERNS}` w prompcie implementera.',
  '3. Hook `check-patterns-read` blokuje zapis, dopóki wzorce nie zostały przeczytane.', '',
  '## Dodawanie wzorca lokalnego', '',
  '1. Plik `<temat>-pattern.md` w `.claude/knowledge/patterns-local/<kategoria>/`.',
  '2. Podłącz go w bloku lokalnym projektu (`.claude/blocks/*.yml`) pełną ścieżką od roota',
  '   — w `patterns.always` albo w grupie `patterns.triggers` — i odpal setup-project.sh.',
  '3. Wzorzec centralny, który tu nie pasuje, usuń z kompozycji przez `patterns.remove`',
  '   w bloku lokalnym (`claude-patterns/blocks/README.md`).', '');

const dst = join(patternsDir, 'README.md');
writeFileSync(dst, out.join('\n'));
console.log(`  patterns/README.md: ${categories.length} kategorii, ${always.length} always, ${useful.length} triggerów`);
